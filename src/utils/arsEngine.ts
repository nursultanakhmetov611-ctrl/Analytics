import type { ArsDataset, ArsReferences, SummaryReportRow, WagonDislocationRow } from '../types/ars.ts';

export function formatSubmissionDate(val: string): string {
  if (!val) return '—';
  const trimmed = String(val).trim();
  if (/^\d{5}$/.test(trimmed)) {
    const serial = parseInt(trimmed, 10);
    const utcDays = serial - 25569;
    const date = new Date(utcDays * 86400 * 1000);
    const dd = String(date.getUTCDate()).padStart(2, '0');
    const mm = String(date.getUTCMonth() + 1).padStart(2, '0');
    const yyyy = date.getUTCFullYear();
    return `${dd}.${mm}.${yyyy}`;
  }
  return trimmed;
}

export function enrichDataset(rawData: any): ArsDataset {
  const enrichedSummary: SummaryReportRow[] = (rawData.summary_reports || []).map((r: any, idx: number) => {
    if (r.section && typeof r.completion_pct === 'number') {
      return r as SummaryReportRow;
    }
    let section = 'Итоговая сводка по холдингу';
    let subSegment = 'ВСЕГО';
    if (idx <= 14) {
      section = 'Парк АО «Казтемиртранс» (КТТ)';
      subSegment = 'КТТ';
    } else if (idx >= 15 && idx <= 37) {
      section = 'Парк собственников и частных операторов';
      subSegment = 'СОБСТВЕННИКИ';
    } else if (idx >= 38 && idx <= 53) {
      section = 'Свод планового ремонта (КТТ + Собственники)';
      subSegment = 'ПЛАНОВЫЙ СВОД';
    } else if (idx >= 54 && idx <= 65) {
      section = 'Текущий отцепочный ремонт (ТОР)';
      subSegment = 'ТОР';
    } else {
      section = 'Генеральная сводка по холдингу АРС';
      subSegment = 'ХОЛДИНГ ИТОГО';
    }

    const pct =
      r.month_plan > 0
        ? Number(((r.done_month / r.month_plan) * 100).toFixed(1))
        : r.done_month > 0
        ? 100
        : 0;

    return {
      ...r,
      row_index: idx,
      section,
      sub_segment: subSegment,
      completion_pct: pct,
    };
  });

  const enrichedDislocations: WagonDislocationRow[] = (rawData.wagon_dislocations_and_stalls || []).map(
    (w: any, idx: number) => ({
      ...w,
      id: w.id || idx + 1,
      formatted_submission_date: w.formatted_submission_date || formatSubmissionDate(w.submission_date),
    })
  );

  return {
    company: rawData.company,
    description: rawData.description,
    depots: rawData.depots || [],
    repair_types: rawData.repair_types || [],
    wagon_types: rawData.wagon_types || [],
    summary_reports: enrichedSummary,
    wagon_dislocations_and_stalls: enrichedDislocations,
    wheel_pairs_production: rawData.wheel_pairs_production || [],
    wheel_pair_stocks: rawData.wheel_pair_stocks || [],
    daily_output_october: rawData.daily_output_october || [],
  };
}

